package me.tbsten.collector.compiler

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertNull

class HintFormatTest {
    @Test
    fun currentMessageRecordsCurrentFormat() {
        assertEquals(CollectorNames.HINT_FORMAT, CollectorNames.hintFormatOf(CollectorNames.HINT_MESSAGE))
    }

    @Test
    fun readsOtherFormats() {
        assertEquals(999, CollectorNames.hintFormatOf("Generated by the Collector compiler plugin (hint format 999). Do not use."))
    }

    @Test
    fun noFormatInAnUnrelatedMessage() {
        assertNull(CollectorNames.hintFormatOf("Use foo() instead"))
    }
}
