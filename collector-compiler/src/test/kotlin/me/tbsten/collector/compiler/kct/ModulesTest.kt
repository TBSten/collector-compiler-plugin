package me.tbsten.collector.compiler.kct

import kotlin.test.Test
import kotlin.test.assertEquals

/** Test plan H (the rest is in integration-tests, which have real Gradle dependency scopes). */
class ModulesTest {
    private val defsFile = "Defs.kt" to """
        package defs
        import me.tbsten.collector.*
        annotation class E
        @CollectorFor<E>() object C : Collector<String>
    """

    /** H4: an item reached through two paths of a diamond appears once. */
    @Test
    fun h4_diamond() {
        val defs = compile("defs", files = arrayOf(defsFile)).requireOk()
        val base = compile("base", listOf(defs), files = arrayOf("Base.kt" to "package base\n@defs.E val b = \"base\"")).requireOk()
        val left = compile("left", listOf(base), files = arrayOf("Left.kt" to "package left\n@defs.E val l = \"left\"")).requireOk()
        val right = compile("right", listOf(base), files = arrayOf("Right.kt" to "package right\n@defs.E val r = \"right\"")).requireOk()
        assertEquals(listOf("base", "left", "right"), box(boxFile("C.collectAsList()"), deps = listOf(left, right)))
    }

    /** H7: hints of an unknown hint format are reported instead of misread (spec 06+). */
    @Test
    fun h7_unknownHintFormat() {
        val old = compile("old", files = arrayOf(
            "Old.kt" to """
                package old
                import me.tbsten.collector.*
                annotation class OldMark
                @CollectorFor<OldMark>() object OldCollector : Collector<String>
            """,
            "Hints.kt" to """
                @file:Suppress("unused", "FunctionName", "UNUSED_PARAMETER")
                package collector.hints
                @Deprecated("Generated by the Collector compiler plugin (hint format 999). Do not use.", level = DeprecationLevel.HIDDEN)
                fun collectorFor_old__OldMark(a: old.OldMark, c: old.OldCollector) {}
                // written before hint formats existed: no format at all
                fun collectorKey_old__OldCollector(a: old.OldMark) {}
            """,
        ), plugin = false).requireOk()
        assertDiagnostics(
            "Use.kt" to """
                import me.tbsten.collector.*
                @old.OldMark val staleItem = "stale" // E: HINT_FORMAT_MISMATCH
                fun f() = old.OldCollector.collectAsList() // E: HINT_FORMAT_MISMATCH
            """,
            deps = listOf(old),
        )
    }
}
