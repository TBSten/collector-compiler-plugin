plugins {
    id("buildsrc.convention.kotlin-jvm")
    `java-gradle-plugin`
}

// BuildConfig: the coordinates and the compiler plugin id from gradle.properties (the single source of truth), so the
// plugin never hard-codes a value that could drift from the published artifacts. Registering the task as a source
// directory wires the dependency for everything that reads the source set.
val generateBuildConfig = tasks.register("generateBuildConfig") {
    val values = mapOf(
        "GROUP" to project.group.toString(),
        "VERSION" to project.version.toString(),
        "COMPILER_PLUGIN_ID" to providers.gradleProperty("COMPILER_PLUGIN_ID").get(),
    )
    val outputDir = layout.buildDirectory.dir("generated/buildConfig/kotlin")
    inputs.properties(values)
    outputs.dir(outputDir)
    val packageName = "me.tbsten.collector.gradle"
    doLast {
        val file = outputDir.get().file("${packageName.replace('.', '/')}/BuildConfig.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            buildString {
                appendLine("// Generated by :collector-gradle-plugin:generateBuildConfig. Do not edit.")
                appendLine("package $packageName")
                appendLine()
                appendLine("internal object BuildConfig {")
                values.forEach { (key, value) -> appendLine("    const val $key: String = \"$value\"") }
                appendLine("}")
            },
        )
    }
}
kotlin.sourceSets.named("main") { kotlin.srcDir(generateBuildConfig) }

dependencies {
    compileOnly(libs.kotlin.gradle.plugin)
}

gradlePlugin {
    plugins {
        create("collector") {
            id = providers.gradleProperty("COMPILER_PLUGIN_ID").get()
            implementationClass = "me.tbsten.collector.gradle.CollectorGradlePlugin"
        }
    }
}
